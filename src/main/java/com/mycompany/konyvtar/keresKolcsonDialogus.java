    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
            // Lekérdezett adat keresése
    String keresesiErtek = kolcsonKeres.getText(); 
    List<Kolcson> keresesiEredmenyek = KonyvtarFrame.kolcsonLista2.keresKolcson(keresesiErtek);

    // Ha nincs találat
    if (keresesiEredmenyek == null || keresesiEredmenyek.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nincs találat!", "Figyelmeztetés", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    // Táblázat oszlopnevei
    String[] oszlopNevek = {"Kölcsön ID", "Könyv ID", "Könyv címe", "Felhasználó ID", "Felhasználó név", "Kölcsön dátum", "Kölcsön határidő"};

    // Adatok átalakítása tömbbé
    Object[][] adatok = new Object[keresesiEredmenyek.size()][oszlopNevek.length];
    for (int i = 0; i < keresesiEredmenyek.size(); i++) {
        Kolcson kolcson = keresesiEredmenyek.get(i);
        adatok[i] = new Object[] {
            kolcson.getId(),
            kolcson.getKonyv().getKonyv_id(),
            kolcson.getKonyv().getKonyv_nev(),
            kolcson.getFelhasznalo().getFelhasznaloID(),
            kolcson.getFelhasznalo().getNev(),
            kolcson.getKolcsondatum(),
            kolcson.getHatarido()
        };
    }

    JTable tabla = new JTable(new DefaultTableModel(adatok, oszlopNevek));
    JScrollPane scrollPane = new JScrollPane(tabla);

    // Felugró ablak létrehozása
    JDialog dialog = new JDialog(this, "Kölcsön keresési eredmények", true);
    dialog.getContentPane().setLayout(new BorderLayout());
    dialog.getContentPane().add(scrollPane, BorderLayout.CENTER);

    // Bezáró gomb létrehozása
    JButton bezarButton = new JButton("Bezár");
    bezarButton.addActionListener(e -> dialog.dispose()); 

    dialog.getContentPane().add(bezarButton, BorderLayout.SOUTH);
    dialog.setSize(600, 350);
    dialog.setLocationRelativeTo(this);
    dialog.setVisible(true);
    dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

