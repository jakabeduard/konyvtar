    private void konyvMentesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_konyvMentesActionPerformed

        Konyv konyv= new Konyv();
        int id=KonyvtarFrame.konyvLista2.getLastID();
        id++;
        konyv.setKonyv_id(id);
        System.out.println(id);

        String cim=konyvCime.getText();
        konyv.setKonyv_nev(cim);

        String szerzo=konyvSzerzo.getText();
        konyv.setSzerzo(szerzo);

        int kiadasiEv = Integer.parseInt(konyvKiadasiEv.getText()); // Szöveg konvertálása számmá
        konyv.setKiadasi_ev(kiadasiEv); // Helyes setter metódus

        String ISBN=konyvISBN.getText();
        konyv.setISBN(ISBN);

        String kiado=konyvKiado.getText();
        konyv.setKiado(kiado);

        boolean kolcsonozheto=false;
        kolcsonozheto = kolcsonozhetoRB.isSelected();
        konyv.setKolcsonozheto(kolcsonozheto);

        KonyvtarFrame.konyvLista2.addKonyv(konyv); 
       
        dispose();


    }//GEN-LAST:event_konyvMentesActionPerformed

