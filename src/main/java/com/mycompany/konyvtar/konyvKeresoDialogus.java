    private void konyvKeresGombActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_konyvKeresGombActionPerformed
      
        String keresett = konyvKeres.getText();
        
         
        // Keresési eredmények lekérdezése
        List<Konyv> keresesiEredmenyek = KonyvtarFrame.konyvLista2.keresKonyv(keresett);

        // Ha nincs találat
        if (keresesiEredmenyek.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nincs találat!", "Figyelmeztetés", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
          dispose();

        // Táblázat oszlopnevek
        String[] oszlopNevek = {"ID", "Könyv Cím", "Szerző", "Kiadás Év", "ISBN", "Kiadó", "Kölcsönözhető"};

        // Adatok átalakítása tömbbé
        Object[][] adatok = new Object[keresesiEredmenyek.size()][oszlopNevek.length];
        for (int i = 0; i < keresesiEredmenyek.size(); i++) {
            Konyv konyv = keresesiEredmenyek.get(i);
            adatok[i] = new Object[] {
                    konyv.getKonyv_id(),
                    konyv.getKonyv_nev(),
                    konyv.getSzerzo(),
                    konyv.getKiadasi_ev(),
                    konyv.getISBN(),
                    konyv.getKiado(),
                    konyv.getKolcsonozheto()
            };
        }

        // JTable létrehozása
        JTable tabla = new JTable(new DefaultTableModel(adatok, oszlopNevek));
        JScrollPane scrollPane = new JScrollPane(tabla);

        // Felugró ablak létrehozása
        JDialog dialog = new JDialog(this, "Keresési eredmények", true);
        dialog.getContentPane().setLayout(new BorderLayout());  // Layout beállítása
        dialog.getContentPane().add(scrollPane, BorderLayout.CENTER);

        // Bezáró gomb létrehozása
        JButton bezarButton = new JButton("Bezár");
        bezarButton.addActionListener(e -> dialog.dispose());  // Bezárja a JDialog ablakot

        dialog.getContentPane().add(bezarButton, BorderLayout.SOUTH);  // Bezár gomb a lenti részre
        dialog.setSize(600, 400);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);


    }//GEN-LAST:event_konyvKeresGombActionPerformed

